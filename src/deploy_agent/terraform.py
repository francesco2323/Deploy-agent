"""Terraform wrapper: saved-plan discipline, hash-pinned plan file, optional emulator (Floci) override."""
from __future__ import annotations

import hashlib
import json
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path

from .runner import CmdError, run

EMULATOR_SERVICES = (
    "s3", "ec2", "iam", "sts", "kms", "eks", "dynamodb", "sqs", "sns", "secretsmanager", "ssm",
    "cloudwatchlogs", "cloudwatch", "lambda", "ecs", "elbv2", "route53", "cloudformation",
    "kinesis", "apigateway", "rds", "sfn", "cognitoidp",
)


@dataclass
class PlanResult:
    path: Path
    sha: str
    plan: dict
    changed: bool


def file_sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


class Terraform:
    def __init__(self, stack_dir: Path, out_dir: Path, tf_bin: str = "terraform", emulator: str | None = None,
                 region: str = "eu-central-1", run_fn=run, log_fn=None):
        self.dir, self.out, self.bin, self.emulator, self.region, self._run = (
            Path(stack_dir), Path(out_dir).resolve(), tf_bin, emulator, region, run_fn)
        self._log_fn = log_fn or (lambda text: None)

    @property
    def plan_path(self) -> Path:
        return self.out / "tfplan"

    def _env(self) -> dict:
        e = {"TF_IN_AUTOMATION": "1", "TF_INPUT": "0"}
        if self.emulator:
            e.update(AWS_ACCESS_KEY_ID="test", AWS_SECRET_ACCESS_KEY="test", AWS_REGION=self.region,
                     AWS_DEFAULT_REGION=self.region)
        return e

    def _override_text(self) -> str:
        eps = "\n".join(f'    {s} = "{self.emulator}"' for s in EMULATOR_SERVICES)
        return (
            "# GENERATED by deploy-agent (emulator mode). Removed after each command.\n"
            'provider "aws" {\n'
            '  access_key = "test"\n  secret_key = "test"\n'
            "  skip_credentials_validation = true\n  skip_metadata_api_check = true\n"
            "  skip_requesting_account_id = true\n  skip_region_validation = true\n  s3_use_path_style = true\n"
            f"  endpoints {{\n{eps}\n  }}\n}}\n"
            "terraform {\n"
            f'  backend "local" {{ path = "{self.out}/terraform.tfstate" }}\n'
            "}\n"
        )

    @contextmanager
    def _session(self):
        p = self.dir / "zz_floci_override.tf"
        if self.emulator:
            p.write_text(self._override_text())
        try:
            yield
        finally:
            if self.emulator:
                p.unlink(missing_ok=True)

    def _tf(self, *args, check=True):
        r = self._run([self.bin, *args], cwd=self.dir, env=self._env(), check=False)
        self._log(args, r)
        if check and r.rc != 0:
            raise CmdError(f"terraform {args[0]} failed rc={r.rc}: {r.err.strip()[-2000:]}")
        return r

    def _log(self, args, r) -> None:
        self.out.mkdir(parents=True, exist_ok=True)
        body = "[json output omitted]" if args[0] in ("show", "output") else (r.out[-6000:] + r.err[-3000:])
        with (self.out / "terraform.log").open("a") as f:
            f.write(f"\n$ terraform {' '.join(args)}\n{body}\n[rc={r.rc}]\n")
        self._log_fn(f"$ terraform {' '.join(args)}\n{body}\n[rc={r.rc}]\n")

    def init(self) -> None:
        with self._session():
            self._tf("init", "-input=false", "-no-color", "-reconfigure")

    def validate(self) -> None:
        with self._session():
            self._tf("validate", "-no-color")

    def show(self, plan_path: Path) -> dict:
        with self._session():
            return json.loads(self._tf("show", "-json", "-no-color", str(plan_path)).out)

    def plan(self, variables: dict) -> PlanResult:
        self.out.mkdir(parents=True, exist_ok=True)
        args = ["plan", "-input=false", "-no-color", "-lock-timeout=60s", "-detailed-exitcode", f"-out={self.plan_path}"]
        for k, v in variables.items():
            args += ["-var", f"{k}={str(v).lower() if isinstance(v, bool) else v}"]
        with self._session():
            r = self._tf(*args, check=False)
        if r.rc not in (0, 2):
            raise CmdError(f"terraform plan failed rc={r.rc}: {r.err.strip()[-2000:]}")
        return PlanResult(self.plan_path, file_sha(self.plan_path), self.show(self.plan_path), r.rc == 2)

    def apply(self, plan_path: Path) -> None:
        with self._session():
            self._tf("apply", "-input=false", "-no-color", "-lock-timeout=60s", str(plan_path))

    def outputs(self) -> dict:
        with self._session():
            return json.loads(self._tf("output", "-json").out or "{}")
